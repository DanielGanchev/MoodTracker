import { MoodEntry, MoodRating } from '@/types'

// Helper function to create a date string for n days ago
const getDaysAgo = (days: number) => {
  const date = new Date()
  date.setDate(date.getDate() - days)
  return date.toISOString()
}

// Helper to generate random number between min and max
const randomBetween = (min: number, max: number) =>
  Math.floor(Math.random() * (max - min + 1) + min)

// Helper to generate random scale values
const generateScaleValues = (base: number, variance: number = 2) => {
  const min = Math.max(1, base - variance)
  const max = Math.min(10, base + variance)
  return randomBetween(min, max)
}

